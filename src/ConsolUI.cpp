string ConsolUI::center(const string& tittle, int width)
{
    string result;
    int spaces = (width - (int)tittle.length()) / 2;
    for (int i = 0; i < spaces; i++)
    {
        result += " ";
    }
    result += tittle;
    for (int i = 0; i < spaces; i++)
    {
        result += " ";
    }
    return result;
}
